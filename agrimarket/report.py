"""Generate a short, plain-language management brief from the computed outputs."""
from __future__ import annotations

import pandas as pd


def _fmt(x, nd=1):
    return "n/a" if pd.isna(x) else f"{x:,.{nd}f}"


def build_brief(commodity, nat, seas, ms, rec, dq, margin) -> str:
    last = nat.dropna(subset=["price_kes_kg"]).iloc[-1]
    peak = nat.loc[nat["price_kes_kg"].idxmax()]
    recent = nat.tail(24)
    peak_m = int(seas.loc[seas["seasonal_index"].idxmax(), "month"]) if not seas.empty else None
    low_m = int(seas.loc[seas["seasonal_index"].idxmin(), "month"]) if not seas.empty else None
    names = ["", "Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"]

    L = [f"# {commodity} market brief: Kenya", "",
         "_Auto-generated by `python -m agrimarket.pipeline`. Figures are traceable to `outputs/*.csv`._", "",
         "## 1. Headlines", "",
         f"- Latest national median retail price ({last['month_start']:%b %Y}): **KES {_fmt(last['price_kes_kg'])}/kg**"
         f" ({_fmt(last['yoy_pct'])}% vs a year earlier, {_fmt(last['mom_pct'])}% vs previous month).",
         f"- Series high: KES {_fmt(peak['price_kes_kg'])}/kg in {peak['month_start']:%b %Y}.",
         f"- Spike months (price >120% of trailing 12-month mean) in the last 24 months: **{int(recent['spike'].sum())}**."]
    if peak_m:
        L.append(f"- Seasonality: prices typically peak around **{names[peak_m]}** and are lowest around **{names[low_m]}**.")

    if not ms.empty:
        top = ms.head(5)
        L += ["", "## 2. Markets to watch", "",
              "Most volatile markets (monthly % change, markets with at least 24 months of data):", "",
              "| Market | Region | Avg KES/kg | Volatility % | Spike rate % | Segment |", "|---|---|---:|---:|---:|---|"]
        for _, r in top.iterrows():
            L.append(f"| {r['market']} | {r['admin1']} | {_fmt(r['avg_price_kes_kg'])} | {_fmt(r['volatility_pct'])} |"
                     f" {_fmt(r['spike_rate_pct'])} | {r['segment']} |")

    if margin is not None and not margin.empty:
        L += ["", f"Median retail-wholesale margin across markets/months: **{_fmt(margin['margin_pct'].median())}%** of the wholesale price."]

    if rec is not None and not rec.empty:
        review = rec[rec["reconciliation_status"].str.startswith("REVIEW")]
        L += ["", "## 3. Cross-source reconciliation (WFP prices vs FAOSTAT production)", "",
              f"- Years compared: {int((rec['production_t'].notna() & rec['price_nominal_kes_kg'].notna()).sum())}.",
              f"- Years flagged for review: **{len(review)}**" + (f" ({', '.join(str(int(y)) for y in review['year'])})." if len(review) else ".")]
        if len(review):
            L.append("- A supply fall without a price rise can reflect imports, stock releases, price controls or a data error; each flagged year needs a human check before it is reported.")

    L += ["", "## 4. Data quality caveats", ""]
    L.append(f"- Checks run: {len(dq)}. Findings by severity: " + ", ".join(f"{k}: {v}" for k, v in dq['severity'].value_counts().items()) + ".")
    for _, r in dq[dq["severity"].isin(["High", "Medium"])].iterrows():
        L.append(f"- {r['check_id']} ({r['dimension']}): {r['description']}: {r['records_affected']:,} records ({r['pct_of_records']}%). Action: {r['action_taken']}.")

    L += ["", "## 5. Suggested actions (for discussion)", ""]
    acts = []
    if last["yoy_pct"] > 20:
        acts.append("Prices are more than 20% above last year: review input-credit and aggregation plans for buyers in the highest-spike markets.")
    elif last["yoy_pct"] < -10:
        acts.append("Prices are well below last year: advise farmers on storage and delayed sales, and check farm-gate margins.")
    if peak_m:
        acts.append(f"Time buyer outreach and storage advice around the seasonal cycle (high around {names[peak_m]}, low around {names[low_m]}).")
    if not ms.empty:
        acts.append("Prioritise price-information services for the 'volatile' market segments, where timing matters most.")
    acts.append("Resolve each High/Medium data-quality finding at source (forms, validation rules) so that it does not recur.")
    L += [f"{i}. {a}" for i, a in enumerate(acts, 1)]
    L += ["", "## 6. Method notes", "",
          "Indicator definitions: `docs/indicator_dictionary.md`. Assumptions and limits: `docs/methodology.md`."]
    return "\n".join(L) + "\n"
